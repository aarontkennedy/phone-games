// Builds src/games/pig/policy.ts: the best play in Pig for every situation, so Hint, the
// Right score and the Strong computer play to win. Run: node scripts/make-pig.mjs
//
// The method is Neller and Presser's: the chance P(i, j, k) that the player about to act
// wins, with score i, the other player's score j, and k points this turn, satisfies
//   hold: 1 - P(j, i + k, 0)                                (a win if i + k reaches the goal)
//   roll: (1 - P(j, i, 0)) / 6 + sum over 2..6 of P(i, j, k + r) / 6
//   P = the better of the two
// and repeating that over every situation until nothing changes gives the exact answer.
import { writeFileSync } from 'node:fs';

export const GOAL = 100;

/** The chance to win in every situation, and whether to hold, by (i, j, k). */
export function solve(goal = GOAL) {
  const idx = (i, j, k) => (i * goal + j) * goal + k;
  const P = new Float64Array(goal * goal * goal);
  const value = (i, j, k) => {
    const hold = i + k >= goal ? 1 : 1 - P[idx(j, i + k, 0)];
    let roll = (1 - P[idx(j, i, 0)]) / 6;
    for (let r = 2; r <= 6; r++) roll += (i + k + r >= goal ? 1 : P[idx(i, j, k + r)]) / 6;
    return { hold, roll };
  };
  for (let delta = 1; delta > 1e-10; ) {
    delta = 0;
    for (let i = 0; i < goal; i++)
      for (let j = 0; j < goal; j++)
        for (let k = 0; i + k < goal; k++) {
          const { hold, roll } = value(i, j, k);
          const v = Math.max(hold, roll);
          delta = Math.max(delta, Math.abs(v - P[idx(i, j, k)]));
          P[idx(i, j, k)] = v;
        }
  }
  /** Holding with nothing this turn is never a choice, so k = 0 always rolls. */
  const holds = (i, j, k) => {
    if (k === 0) return false;
    const { hold, roll } = value(i, j, k);
    return hold >= roll - 1e-12;
  };
  return { win: (i, j, k) => P[idx(i, j, k)], holds };
}

/**
 * The table as text: for each (i, j), row by row, the turn totals where the best play
 * switches between rolling and holding (it starts as rolling at 0), each as two base-36
 * digits, rows separated by commas.
 */
export function encode(holds, goal = GOAL) {
  const rows = [];
  for (let i = 0; i < goal; i++)
    for (let j = 0; j < goal; j++) {
      let row = '';
      let holding = false;
      for (let k = 0; i + k < goal; k++) {
        if (holds(i, j, k) !== holding) {
          row += k.toString(36).padStart(2, '0');
          holding = !holding;
        }
      }
      rows.push(row);
    }
  return rows.join(',');
}

if (process.argv[1]?.endsWith('make-pig.mjs')) {
  const { win, holds } = solve();
  const table = encode(holds);
  writeFileSync(
    new URL('../src/games/pig/policy.ts', import.meta.url),
    `// Generated by scripts/make-pig.mjs: the best play in Pig (to ${GOAL}) for every situation.\n` +
      `// For each of your score and theirs, the turn totals where the best play switches between\n` +
      `// rolling and holding, two base-36 digits each. Don't edit by hand.\n` +
      `/** The first player's chance to win, playing perfectly against perfect play. */\n` +
      `export const FIRST_PLAYER_WINS = ${win(0, 0, 0).toFixed(6)};\n` +
      `export const TABLE = ${JSON.stringify(table)};\n`,
  );
  console.log(`Wrote the table: ${table.length} characters. First player wins ${win(0, 0, 0).toFixed(4)}.`);
}
